"""Grounded NPC knowledge from authoritative game state.

Exploration events are generated by EventAgent only. This module reads the
completed-event journal and provides *potential* rumors without executing an
event or treating old LLM dialogue as evidence. No network or LLM dependency.
"""
from __future__ import annotations

import hashlib
import re
from typing import Any, Dict, List, Optional

from agents.event_agent import EventAgent

# These events could plausibly become public knowledge. Private player finds
# (coins, footprints, secret paths) are NOT automatically known to every NPC.
PUBLIC_EVENT_REPORTS = {
    "npc_encounter": "a traveler was encountered",
    "traveler_in_need": "a traveler needed help",
    "enemy_ambush": "someone encountered a hostile enemy",
    "bandit_roadblock": "bandits blocked the road",
    "guard_patrol": "a guard patrol was seen",
    "merchant_cart": "a merchant cart was seen on the road",
    "old_ruin_discovery": "old ruins were discovered",
}

# Potential scenarios drawn from EventAgent's existing event IDs. Rumors are
# explicitly unconfirmed, and NEVER inserted into recent_events/pending_events.
RUMOR_TEMPLATES = {
    "strange_noise": "Some travelers speak of strange sounds outside town, but I can't confirm that.",
    "bandit_roadblock": "There is talk of bandits on the roads, though I have no confirmed report.",
    "old_ruin_discovery": "People speculate about forgotten ruins, but I have no proof of any discovery.",
    "merchant_cart": "Some say a trading caravan might pass through soon, but that's only a rumor.",
    "traveler_in_need": "I've heard speculation that a traveler might need help somewhere, but nothing is confirmed.",
}
assert set(PUBLIC_EVENT_REPORTS) <= set(EventAgent.EVENT_DESCRIPTIONS)
assert set(RUMOR_TEMPLATES) <= set(EventAgent.EVENT_DESCRIPTIONS)


def is_stock_question(player_input: str, target: str) -> bool:
    if str(target).lower() != "merchant":
        return False
    text = str(player_input or "").lower()
    # General shopping requests are inventory questions even when the player
    # does not use the words 'stock', 'goods', or 'sell'.
    if re.search(
        r"\b(?:what (?:do|can) you have (?:for me|to offer)|"
        r"what (?:have|got) you got (?:for me|to offer)|"
        r"what can you offer(?: me)?|"
        r"show me (?:what you have|your wares)|"
        r"what do you have (?:for sale|available))\b", text,
    ):
        return True
    return bool(re.search(
        r"\b(?:stock|restock|shipment|deliver(?:y|ies|ed)?|new arrivals?|"
        r"inventory|wares|goods|items?|prices?|how much|"
        r"what do you sell|what are you selling|do you sell|"
        r"do you have (?:any |some |a |an )?(?:goods|items|wares|stock|"
        r"supplies|equipment|weapons?|potions?|swords?|rings?|ropes?|"
        r"backpacks?|lanterns?)|"
        r"have you got (?:any |some )?(?:goods|items|wares|stock|supplies|"
        r"weapons?|potions?|swords?|rings?)|"
        r"got anything new|anything new|backpacks?|lanterns?)\b", text
    ))


def information_request_kind(player_input: str, target: str) -> Optional[str]:
    """Identify the requested *information*, not just matching nouns.

    Separating a stock list from delivery news prevents a previous NPC answer
    from overriding the player's latest clarification. Extend this registry
    when new authoritative information sources are added.
    """
    if is_stock_question(player_input, target):
        text = str(player_input or "").lower()
        if re.search(r"\b(?:new|newly|latest|recent|recently|fresh|"
                     r"restock(?:ed|ing)?|shipments?|deliver(?:y|ies|ed)|"
                     r"arrivals?)\b", text):
            return "stock_updates"
        return "stock_overview"
    if is_news_question(player_input):
        return "world_news"
    return None


def information_response_issue(
    request_kind: Optional[str], reply: str, game_state: Dict[str, Any],
    target: str,
) -> Optional[str]:
    """Reject responses to the WRONG information request, for any NPC.

    Structural relevance checks complement the existing factual validator.
    They never treat a generated statement as evidence about world state.
    """
    if request_kind is None:
        return None
    text = str(reply or "").lower()
    if request_kind == "stock_overview":
        # Specifically avoid answering general availability with delivery news.
        if re.search(r"\b(?:no|not|haven't|have not|can't|cannot|without)\b.{0,85}"
                     r"\b(?:deliver(?:y|ies)|shipments?|restock|arrivals?)\b", text):
            return "Asked for current goods, but answered about deliveries instead."
        # Relevance is not a vocabulary exam. The NPC may offer to help,
        # ask what the player seeks or describe its trade without saying
        # 'stock', 'goods', or 'inventory'. Hard factual claims are checked
        # independently by DialogueValidatorAgent.
    # No other text-style or keyword constraints. A fluent answer about the
    # requested subject must not be discarded merely for wording differences.
    return None


def is_news_question(player_input: str) -> bool:
    text = str(player_input or "").lower().strip()
    if re.search(r"\b(?:news|rumou?rs?|gossip|heard anything|anything unusual|"
                 r"strange occurrences|latest happenings|any updates)\b", text):
        return True
    return bool(re.fullmatch(
        r"(?:what happened|what's happening|what is happening)"
        r"(?: around here| in town| lately)?[?.!]*", text
    ))


def public_events(game_state: Dict[str, Any], target: str = "") -> List[Dict[str, str]]:
    """Read only occurred, public events; never infer facts from LLM memories."""
    results = []
    journal = game_state.get("recent_events", [])
    if not isinstance(journal, list):
        return results
    for record in reversed(journal):
        if not isinstance(record, dict):
            continue
        event_id = str(record.get("event", ""))
        if event_id not in PUBLIC_EVENT_REPORTS:
            continue
        # Legacy EventAgent journal records had no status, but were written
        # only by generate_followup_event after apply_event_result.
        if record.get("status", "occurred") not in {"occurred", "confirmed"}:
            continue
        known_to = record.get("known_to")
        if known_to is not None:
            if not isinstance(known_to, (list, tuple, set)) or target not in known_to:
                continue
        results.append({
            "event": event_id,
            "report": PUBLIC_EVENT_REPORTS[event_id],
            "location": str(record.get("location") or "").strip(),
        })
        if len(results) >= 3:
            break
    return results


def format_verified_events(game_state: Dict[str, Any], target: str) -> str:
    events = public_events(game_state, target)
    if not events:
        return "- No confirmed public events are known to this NPC."
    return "\n".join(
        "- Confirmed public event: " + event["report"] +
        (" at " + event["location"] if event["location"] else "")
        for event in events
    )


def _rumor_for(target: str, game_state: Dict[str, Any]) -> str:
    location = str(game_state.get("location", ""))
    # Stable choice for a location/NPC, not a random event roll.
    choices = tuple(RUMOR_TEMPLATES)
    digest = hashlib.sha256(f"{target}:{location}".encode("utf-8")).digest()
    return RUMOR_TEMPLATES[choices[int.from_bytes(digest[:4], "big") % len(choices)]]


def grounded_news_reply(game_state: Dict[str, Any], target: str) -> str:
    events = public_events(game_state, target)
    if events:
        latest = events[0]
        place = f" near {latest['location']}" if latest["location"] else ""
        return f"I've heard that {latest['report']}{place}. That's the latest confirmed report I know."
    return "I haven't heard any confirmed news. " + _rumor_for(target, game_state)


def confirmed_shipments(game_state: Dict[str, Any], target: str) -> List[Dict[str, Any]]:
    """Only explicit completed deliveries; merchant_cart is NOT a shipment."""
    shipments = game_state.get("merchant_shipments", [])
    if not isinstance(shipments, list):
        return []
    return [
        item for item in shipments
        if isinstance(item, dict)
        and item.get("status") in {"occurred", "confirmed", "delivered"}
        and item.get("merchant", "merchant") == target
    ]


def _verified_stock(game_state: Dict[str, Any], target: str) -> Optional[List[str]]:
    """Never mistake the player's `inventory` for merchant inventory."""
    for key in ("merchant_stock", "merchant_inventory", "shop_inventory"):
        if key not in game_state:
            continue
        value = game_state[key]
        if isinstance(value, dict):
            value = value.get(target, value) if target in value else value
            if isinstance(value, dict):
                return [str(k) for k, qty in value.items() if isinstance(qty, (int, float)) and qty > 0]
        if isinstance(value, list):
            names = []
            for item in value:
                if isinstance(item, dict):
                    qty = item.get("quantity", item.get("stock", 1))
                    if not isinstance(qty, (int, float)) or qty <= 0:
                        continue
                    name = str(item.get("name", "")).strip()
                else:
                    name = str(item).strip()
                if name:
                    names.append(name)
            return names
    return None


def grounded_stock_reply(game_state: Dict[str, Any], player_input: str, target: str) -> str:
    text = str(player_input or "").lower()
    asks_new = bool(re.search(r"\b(?:new|latest|recent|shipment|delivery|deliveries|restock|arrivals?)\b", text))
    if asks_new:
        shipments = confirmed_shipments(game_state, target)
        if not shipments:
            return "I haven't had any confirmed new deliveries to report. What supplies are you looking for?"
        latest = shipments[-1]
        items = latest.get("items")
        if isinstance(items, list) and items:
            return "The latest confirmed delivery brought " + ", ".join(map(str, items[:3])) + "."
        return "A delivery has been confirmed, though I don't have an itemized list for you."
    stock = _verified_stock(game_state, target)
    if stock is None:
        return "I deal in supplies for travelers, but I can't confirm my current stock right now."
    if not stock:
        return "I don't have any confirmed goods available right now."
    return "I currently have " + ", ".join(stock[:4]) + ". What interests you?"



# Short, context-dependent requests should refer to the last NPC utterance,
# rather than being treated as a fresh greeting or a request for new news.
FOLLOWUP_PATTERN = re.compile(
    r"^\s*(?:tell me more(?: about (?:that|it|this))?|"
    r"(?:can|could) you (?:tell|say) (?:me )?more(?: about (?:that|it))?|"
    r"(?:what|how) (?:about|do you mean by) (?:that|it)|"
    r"(?:and )?then what|what happened next|"
    r"what else(?: do you know)?|"
    r"(?:is (?:that|it) true|are you sure)|"
    r"(?:when|where|why|who|how)(?: exactly)?(?:\s+.*)?|"
    r"go on|continue|elaborate|any details(?: about (?:that|it))?)\s*[?.!]*\s*$",
    re.I,
)

# These are not new events: just topics that can be recognized in an NPC's
# PREVIOUS utterance. They never become facts by being mentioned in dialogue.
RUMOR_TOPICS = (
    (re.compile(r"\b(?:caravan|merchant cart|trading wagon)\b", re.I),
     "a trading caravan might pass through", "a caravan's route or arrival"),
    (re.compile(r"\b(?:bandits?|roadblock)\b", re.I),
     "there might be bandits on the roads", "any reported attack or location"),
    (re.compile(r"\b(?:strange sounds?|strange noises?)\b", re.I),
     "people have mentioned strange sounds", "what caused those sounds"),
    (re.compile(r"\b(?:ruins?|ancient site)\b", re.I),
     "people have speculated about old ruins", "a discovery or exact location"),
    (re.compile(r"\b(?:traveler|traveller)\b.*\b(?:help|need)\b", re.I),
     "someone may need help", "who or where that person is"),
)


# A short intent to investigate the previous story is a conversational response,
# even when it does not contain a literal question word or the word "rumor".
# Keep this deliberately narrow: "check my order" is not a rumor follow-up.
INVESTIGATION_FOLLOWUP_PATTERN = re.compile(
    r"^\s*(?:i\s+(?:want|would like|plan|intend|hope|need)\s+to\s+"
    r"(?:go\s+(?:and\s+)?|go\s+to\s+)?(?:check|investigate|verify|look\s+into|"
    r"find\s+out\s+about)"
    r"|i(?:'ll|\s+will|\s+can|\s+could|\s+might)\s+"
    r"(?:go\s+(?:and\s+)?)?(?:check|investigate|verify|look\s+into)"
    r"|(?:can|could|should|may)\s+i\s+(?:go\s+(?:and\s+)?)?"
    r"(?:check|investigate|verify|look\s+into))"
    r"(?:\s+(?:it|that|this|the\s+(?:story|rumou?r|report|caravan|road)))?"
    r"\s*[?.!]*\s*$",
    re.I,
)

SERVICE_REQUEST_PATTERN = re.compile(
    r"\b(?:order(?:ed|ing)?|buy|bought|purchase(?:d)?|"
    r"(?:serve|served|bring|brought|pour|poured)\s+(?:me\s+)?)\b"
    r".*\b(?:wine|mead|beer|ale|drink|water|food)\b",
    re.I,
)


def _is_service_turn(turn: Dict[str, Any]) -> bool:
    intent = str(turn.get("intent") or "").strip().lower()
    if intent == "tavern_action":
        return True
    # Legacy history records have only player/npc fields.
    return bool(SERVICE_REQUEST_PATTERN.search(str(turn.get("player") or "")))


def _latest_conversation_turn(conversation_history: Any) -> Optional[Dict[str, Any]]:
    """Last substantive NPC exchange, ignoring side actions such as drinks.

    A newer unrelated dialogue IS a topic change and stops the search; we must
    not resurrect an old rumor after the player has moved on to another subject.
    """
    if not isinstance(conversation_history, list):
        return None
    for turn in reversed(conversation_history):
        if not isinstance(turn, dict):
            continue
        if _is_service_turn(turn):
            continue
        if str(turn.get("npc") or "").strip():
            return turn
    return None


def news_followup_anchor(player_input: str, conversation_history: Any) -> Optional[Dict[str, Any]]:
    """Return the earlier news turn only for a contextual, on-topic follow-up."""
    if not is_context_followup(player_input, conversation_history):
        return None
    turn = _latest_conversation_turn(conversation_history)
    if not turn:
        return None
    previous = str(turn.get("npc") or "")
    previous_lower = previous.lower()
    if (re.search(r"\b(?:rumou?r|confirmed news|confirmed report|heard|speculat|"
                  r"not confirmed|can't confirm|might|no proof|whispers)\b", previous_lower)
            or any(pattern.search(previous) for pattern, _, _ in RUMOR_TOPICS)):
        return turn
    return None


def is_context_followup(player_input: str, conversation_history: Any) -> bool:
    """A referential follow-up to the last substantive NPC dialogue."""
    if _latest_conversation_turn(conversation_history) is None:
        return False
    text = str(player_input or "")
    return bool(FOLLOWUP_PATTERN.fullmatch(text)
                or INVESTIGATION_FOLLOWUP_PATTERN.fullmatch(text))


def is_news_followup(player_input: str, conversation_history: Any) -> bool:
    """Follow-up to earlier news even if a deterministic service action intervened."""
    return news_followup_anchor(player_input, conversation_history) is not None


# Conversational follow-ups may contain additional intentions ("I seek adventures")
# instead of matching the older narrow full-sentence regex.
CREATIVE_FOLLOWUP_START = re.compile(
    r"^\s*(?:(?:can|could|would) you\s+)?(?:please\s+)?"
    r"(?:tell me more|say more|go on|continue|elaborate|any details|what happened next)\b",
    re.I,
)


def creative_followup_anchor(player_input: str, conversation_history: Any) -> Optional[Dict[str, Any]]:
    """Resolve an explicit follow-up to the last substantive NPC utterance.

    Drink purchases are interruptions, not new conversation topics. A player
    who makes a different substantive request is a topic change.
    """
    text = str(player_input or "").strip()
    if not (CREATIVE_FOLLOWUP_START.search(text)
            or is_context_followup(text, conversation_history)):
        return None
    return _latest_conversation_turn(conversation_history)


def missing_followup_subject(player_input: str, history: Any, reply: str) -> bool:
    """Detect an obvious subject switch; never police invented story details.

    Only enforce explicit recognizable topics. For unknown stories, let the LLM
    improvise rather than apply arbitrary lexical similarity thresholds.
    """
    anchor = creative_followup_anchor(player_input, history)
    if not anchor:
        return False
    previous = str(anchor.get("npc") or "")
    response = str(reply or "")
    # The last story may contain a passing second topic. For now anchor on the
    # first identifiable topic, not every word the NPC previously said.
    matches = [(m.start(), pattern) for pattern, _, _ in RUMOR_TOPICS
               for m in [pattern.search(previous)] if m]
    if not matches:
        return False
    _, pattern = min(matches, key=lambda item: item[0])
    return not bool(pattern.search(response))


def missing_investigation_topic(player_input: str, conversation_history: Any, reply: str) -> bool:
    """Flag generic answers that forget the subject of a short investigation follow-up.

    Only applies to known, previously mentioned rumor subjects and narrow
    referential player utterances. This is dialogue coherence checking, not
    evidence that the rumored event actually happened.
    """
    if not INVESTIGATION_FOLLOWUP_PATTERN.fullmatch(str(player_input or "")):
        return False
    anchor = news_followup_anchor(player_input, conversation_history)
    if not anchor:
        return False
    previous = str(anchor.get("npc") or "")
    response = str(reply or "")
    for pattern, _, _ in RUMOR_TOPICS:
        if pattern.search(previous):
            return not bool(pattern.search(response))
    return False


def grounded_followup_reply(
    game_state: Dict[str, Any], target: str, player_input: str,
    conversation_history: Any,
) -> Optional[str]:
    """Safely continue an existing news/rumor thread, with no new world facts.

    A rumor is conversation context, NEVER an authoritative world event.
    This is a safe fallback for short referential follow-ups that otherwise
    tend to generate invented details or generic 'Speak plainly' replies.
    """
    if not is_news_followup(player_input, conversation_history):
        return None
    previous = str(news_followup_anchor(player_input, conversation_history).get("npc") or "")
    question = str(player_input or "").strip().lower()
    # A confirmed public event can be expanded only with verified location.
    for event in public_events(game_state, target):
        if event["report"].lower() in previous.lower():
            location = event["location"]
            if re.match(r"^where\b", question):
                return (f"The report places it near {location}." if location else
                        "I don't have a confirmed location for it.")
            if re.match(r"^when\b", question):
                return "I know it happened, but I don't have a confirmed time."
            return (f"What I can confirm is that {event['report']}"
                    + (f" near {location}" if location else "")
                    + ". I don't have more verified details yet.")

    for pattern, possibility, unknown in RUMOR_TOPICS:
        if not pattern.search(previous):
            continue
        if re.match(r"^(?:is (?:that|it) true|are you sure)\b", question):
            return "I can't say it's true. It's only a rumor, not a confirmed report."
        if re.match(r"^who\b", question):
            return "I can't verify who started that story. It's only hearsay."
        if re.match(r"^where\b", question):
            return "I haven't heard a confirmed location. I wouldn't trust guesses."
        if re.match(r"^when\b", question):
            return "I haven't heard a confirmed time, and I wouldn't want to mislead you."
        return (f"All I've heard is that {possibility}. "
                f"I can't confirm {unknown}, so I wouldn't treat it as fact.")

    # Unknown old rumor: don't fabricate an explanation or invent a new one.
    return "I don't have any more reliable details about that story yet."


def grounded_reply(game_state: Dict[str, Any], target: str, player_input: str) -> Optional[str]:
    if is_stock_question(player_input, target):
        return grounded_stock_reply(game_state, player_input, target)
    if is_news_question(player_input):
        return grounded_news_reply(game_state, target)
    return None
